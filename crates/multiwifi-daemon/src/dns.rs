#![deny(unsafe_code)]

use std::env;
use std::fs::{self, OpenOptions};
use std::io::{self, Write};
use std::net::IpAddr;
use std::os::unix::fs::OpenOptionsExt;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::Duration;
use thiserror::Error;
use zbus::Connection;

const MAX_DNS_SERVERS: usize = 16;
const DEFAULT_NM_DNS_CONF: &str = "/etc/NetworkManager/conf.d/99-multiwifi-dns.conf";
const DEFAULT_RESOLV_CONF: &str = "/etc/resolv.conf";
const DEFAULT_RESOLV_BACKUP: &str = "/run/multiwifi/resolv.conf.bak";

static TMP_SEQ: AtomicU64 = AtomicU64::new(0);

#[derive(Debug, Error)]
pub enum DnsError {
    #[error("{0}")]
    InvalidArgument(String),

    #[error("refusing to follow symbolic link target '{0}'")]
    SymlinkForbidden(String),

    #[error("DNS file operation failed: {0}")]
    Io(#[from] io::Error),
}

#[derive(Debug, Clone)]
pub struct DnsPaths {
    pub nm_conf: PathBuf,
    pub resolv_conf: PathBuf,
    pub resolv_backup: PathBuf,
    pub has_test_override: bool,
}

impl DnsPaths {
    #[must_use]
    pub fn from_env() -> Self {
        let conf_dir = env::var_os("MULTIWIFI_DNS_CONF_DIR").filter(|s| !s.is_empty());
        let resolv_override = env::var_os("MULTIWIFI_RESOLV_CONF").filter(|s| !s.is_empty());
        let has_test_override = conf_dir.is_some() || resolv_override.is_some();

        let (nm_conf, resolv_backup) = match conf_dir {
            Some(dir) => {
                let d = PathBuf::from(dir);
                (d.join("99-multiwifi-dns.conf"), d.join("resolv.conf.bak"))
            }
            None => (
                PathBuf::from(DEFAULT_NM_DNS_CONF),
                PathBuf::from(DEFAULT_RESOLV_BACKUP),
            ),
        };

        let resolv_conf = match resolv_override {
            Some(path) => PathBuf::from(path),
            None => PathBuf::from(DEFAULT_RESOLV_CONF),
        };

        Self {
            nm_conf,
            resolv_conf,
            resolv_backup,
            has_test_override,
        }
    }
}

pub fn validate_dns_servers(servers: &[String]) -> Result<Vec<String>, DnsError> {
    if servers.len() > MAX_DNS_SERVERS {
        return Err(DnsError::InvalidArgument(format!(
            "Too many DNS servers specified (maximum {MAX_DNS_SERVERS})"
        )));
    }

    let mut clean = Vec::with_capacity(servers.len());
    for raw in servers {
        let trimmed = raw.trim();
        if trimmed.is_empty() || trimmed.parse::<IpAddr>().is_err() {
            return Err(DnsError::InvalidArgument(
                "Invalid DNS configuration: must provide 1-16 valid IPv4 or IPv6 addresses"
                    .to_owned(),
            ));
        }
        clean.push(trimmed.to_owned());
    }

    if clean.is_empty() {
        return Err(DnsError::InvalidArgument(
            "Invalid DNS configuration: must provide 1-16 valid IPv4 or IPv6 addresses".to_owned(),
        ));
    }

    Ok(clean)
}

#[must_use]
pub fn read_current_dns_servers(paths: &DnsPaths) -> Vec<String> {
    let Ok(content) = fs::read_to_string(&paths.resolv_conf) else {
        return Vec::new();
    };

    let mut servers = Vec::new();
    for line in content.lines() {
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix("nameserver") {
            if !rest.is_empty() && !rest.starts_with(char::is_whitespace) {
                continue;
            }
            if let Some(ip_str) = rest.split_whitespace().next() {
                if ip_str.parse::<IpAddr>().is_ok() {
                    servers.push(ip_str.to_owned());
                }
            }
        }
    }
    servers
}

#[must_use]
pub fn is_custom_dns_active(paths: &DnsPaths) -> bool {
    fs::symlink_metadata(&paths.nm_conf).is_ok()
}

pub fn apply_dns_configuration(paths: &DnsPaths, servers: &[String]) -> Result<(), DnsError> {
    let clean = validate_dns_servers(servers)?;
    reject_if_symlink(&paths.nm_conf)?;
    reject_if_symlink(&paths.resolv_backup)?;

    let nm_content = format!(
        "# Generated by MultiWiFi\n[global-dns]\nsearches=\n\n[global-dns-domain-*]\nservers={}\n",
        clean.join(",")
    );
    write_atomic_nofollow(&paths.nm_conf, &nm_content)?;

    // Preserve system symlinks (e.g. systemd-resolved stub resolver).
    if is_symlink(&paths.resolv_conf)? {
        return Ok(());
    }

    if !path_exists_nofollow(&paths.resolv_backup)? && path_exists_nofollow(&paths.resolv_conf)? {
        let orig = read_nofollow(&paths.resolv_conf)?;
        write_atomic_nofollow(&paths.resolv_backup, &orig)?;
    }

    let mut resolv_content = String::from("# Generated by MultiWiFi\n");
    for s in &clean {
        resolv_content.push_str("nameserver ");
        resolv_content.push_str(s);
        resolv_content.push('\n');
    }
    write_atomic_nofollow(&paths.resolv_conf, &resolv_content)?;
    Ok(())
}

pub fn reset_dns_configuration(paths: &DnsPaths) -> Result<(), DnsError> {
    if is_symlink(&paths.nm_conf)? {
        return Err(DnsError::SymlinkForbidden(
            paths.nm_conf.display().to_string(),
        ));
    }
    if path_exists_nofollow(&paths.nm_conf)? {
        fs::remove_file(&paths.nm_conf)?;
    }

    if path_exists_nofollow(&paths.resolv_backup)? {
        reject_if_symlink(&paths.resolv_backup)?;
        reject_if_symlink(&paths.resolv_conf)?;

        let backup_content = read_nofollow(&paths.resolv_backup)?;
        write_atomic_nofollow(&paths.resolv_conf, &backup_content)?;
        let _ = fs::remove_file(&paths.resolv_backup);
    }
    Ok(())
}

pub async fn notify_nm_reload_async(
    conn: Option<&Connection>,
    is_system_bus: bool,
    paths: &DnsPaths,
) {
    if !is_system_bus || paths.has_test_override {
        return;
    }
    let Some(c) = conn else {
        return;
    };
    let call = c.call_method(
        Some("org.freedesktop.NetworkManager"),
        "/org/freedesktop/NetworkManager",
        Some("org.freedesktop.NetworkManager"),
        "Reload",
        &(0x3u32),
    );
    let _ = tokio::time::timeout(Duration::from_secs(3), call).await;
}

fn is_symlink(path: &Path) -> io::Result<bool> {
    match fs::symlink_metadata(path) {
        Ok(meta) => Ok(meta.file_type().is_symlink()),
        Err(err) if err.kind() == io::ErrorKind::NotFound => Ok(false),
        Err(err) => Err(err),
    }
}

fn path_exists_nofollow(path: &Path) -> io::Result<bool> {
    match fs::symlink_metadata(path) {
        Ok(_) => Ok(true),
        Err(err) if err.kind() == io::ErrorKind::NotFound => Ok(false),
        Err(err) => Err(err),
    }
}

fn reject_if_symlink(path: &Path) -> Result<(), DnsError> {
    if is_symlink(path)? {
        return Err(DnsError::SymlinkForbidden(path.display().to_string()));
    }
    Ok(())
}

fn read_nofollow(path: &Path) -> Result<String, DnsError> {
    let mut file = OpenOptions::new()
        .read(true)
        .custom_flags(libc::O_NOFOLLOW | libc::O_CLOEXEC)
        .open(path)?;
    let mut out = String::new();
    io::Read::read_to_string(&mut file, &mut out)?;
    Ok(out)
}

fn write_atomic_nofollow(path: &Path, content: &str) -> Result<(), DnsError> {
    reject_if_symlink(path)?;
    let parent = path.parent().filter(|p| !p.as_os_str().is_empty()).ok_or_else(|| {
        io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("missing parent directory for '{}'", path.display()),
        )
    })?;
    fs::create_dir_all(parent)?;

    let file_name = path
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("dns");
    let seq = TMP_SEQ.fetch_add(1, Ordering::Relaxed);
    let tmp_path = parent.join(format!(".{file_name}.{}.{seq}.tmp", std::process::id()));

    let write_res = (|| -> io::Result<()> {
        let mut f = OpenOptions::new()
            .write(true)
            .create_new(true)
            .mode(0o644)
            .custom_flags(libc::O_NOFOLLOW | libc::O_CLOEXEC)
            .open(&tmp_path)?;
        f.write_all(content.as_bytes())?;
        f.sync_all()?;
        Ok(())
    })();

    if let Err(err) = write_res {
        let _ = fs::remove_file(&tmp_path);
        return Err(DnsError::Io(err));
    }

    if let Err(err) = reject_if_symlink(path) {
        let _ = fs::remove_file(&tmp_path);
        return Err(err);
    }

    if let Err(err) = fs::rename(&tmp_path, path) {
        let _ = fs::remove_file(&tmp_path);
        return Err(DnsError::Io(err));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::os::unix::fs::symlink;

    #[test]
    fn dns_validation_and_roundtrip() {
        let dir = tempfile::tempdir().expect("tempdir");
        let resolv = dir.path().join("resolv.conf");
        fs::write(&resolv, "nameserver 192.168.1.1\n").expect("seed resolv");

        let paths = DnsPaths {
            nm_conf: dir.path().join("99-multiwifi-dns.conf"),
            resolv_conf: resolv.clone(),
            resolv_backup: dir.path().join("resolv.conf.bak"),
            has_test_override: true,
        };

        assert!(!is_custom_dns_active(&paths));
        assert_eq!(read_current_dns_servers(&paths), vec!["192.168.1.1"]);

        // Reject invalid IP, empty list, and >16 entries
        assert!(matches!(
            apply_dns_configuration(&paths, &["invalid.not.an.ip".to_owned()]).unwrap_err(),
            DnsError::InvalidArgument(_)
        ));
        assert!(matches!(
            apply_dns_configuration(&paths, &[]).unwrap_err(),
            DnsError::InvalidArgument(_)
        ));
        let too_many: Vec<String> = (1..=17).map(|i| format!("1.1.1.{i}")).collect();
        assert!(matches!(
            apply_dns_configuration(&paths, &too_many).unwrap_err(),
            DnsError::InvalidArgument(_)
        ));

        // Happy path apply -> verify -> reset
        apply_dns_configuration(&paths, &["1.1.1.1".to_owned(), "2606:4700:4700::1111".to_owned()])
            .expect("apply dns");
        assert!(is_custom_dns_active(&paths));
        assert_eq!(
            read_current_dns_servers(&paths),
            vec!["1.1.1.1", "2606:4700:4700::1111"]
        );

        reset_dns_configuration(&paths).expect("reset dns");
        assert!(!is_custom_dns_active(&paths));
        assert_eq!(read_current_dns_servers(&paths), vec!["192.168.1.1"]);
    }

    #[test]
    fn dns_refuses_symlinks_on_nm_conf() {
        let dir = tempfile::tempdir().expect("tempdir");
        let resolv = dir.path().join("resolv.conf");
        let victim = dir.path().join("victim.txt");
        let nm_conf = dir.path().join("99-multiwifi-dns.conf");
        fs::write(&resolv, "nameserver 8.8.8.8\n").expect("seed");
        symlink(&victim, &nm_conf).expect("symlink");

        let paths = DnsPaths {
            nm_conf,
            resolv_conf: resolv,
            resolv_backup: dir.path().join("resolv.conf.bak"),
            has_test_override: true,
        };

        let err = apply_dns_configuration(&paths, &["1.1.1.1".to_owned()]).unwrap_err();
        assert!(matches!(err, DnsError::SymlinkForbidden(_)));
        assert!(!victim.exists());
    }
}
